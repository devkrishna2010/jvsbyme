def _template_racing_game() -> str:
    return '''"""
Autonomous 2D Racing Game — Generated by J.A.R.V.I.S. V2
Smooth Tkinter Canvas 60 FPS rendering with zero external dependencies.
Controls: Left / Right Arrow keys to steer, 'R' to restart, 'Q' to quit.
"""
import tkinter as tk
import random

class RacingGame:
    def __init__(self, root):
        self.root = root
        self.root.title("J.A.R.V.I.S. Tactical Racing Simulation — Stark Mk VII")
        self.root.resizable(False, False)
        
        self.width = 400
        self.height = 600
        self.canvas = tk.Canvas(root, width=self.width, height=self.height, bg="#111822", highlightthickness=0)
        self.canvas.pack()
        
        # Player Car attributes
        self.player_w = 40
        self.player_h = 70
        self.player_x = (self.width - self.player_w) // 2
        self.player_y = self.height - self.player_h - 30
        self.speed = 7
        
        # Obstacle Cars
        self.enemies = []
        self.score = 0
        self.running = True
        self.game_over = False
        
        # Road markings
        self.road_stripes = [i * 80 for i in range(8)]
        
        # Key bindings
        self.keys = {"Left": False, "Right": False}
        self.root.bind("<Left>", lambda e: self.set_key("Left", True))
        self.root.bind("<KeyRelease-Left>", lambda e: self.set_key("Left", False))
        self.root.bind("<Right>", lambda e: self.set_key("Right", True))
        self.root.bind("<KeyRelease-Right>", lambda e: self.set_key("Right", False))
        self.root.bind("r", lambda e: self.reset())
        self.root.bind("R", lambda e: self.reset())
        self.root.bind("q", lambda e: self.root.destroy())
        self.root.bind("Q", lambda e: self.root.destroy())

        self.spawn_timer = 0
        self.update_loop()

    def set_key(self, key, state):
        self.keys[key] = state

    def reset(self):
        self.player_x = (self.width - self.player_w) // 2
        self.enemies = []
        self.score = 0
        self.game_over = False
        self.running = True

    def update_loop(self):
        if not self.game_over:
            # Handle player movement
            if self.keys["Left"] and self.player_x > 40:
                self.player_x -= self.speed
            if self.keys["Right"] and self.player_x < self.width - 40 - self.player_w:
                self.player_x += self.speed

            # Move road stripes
            for i in range(len(self.road_stripes)):
                self.road_stripes[i] += 8
                if self.road_stripes[i] > self.height:
                    self.road_stripes[i] = -60

            # Spawn obstacle cars
            self.spawn_timer += 1
            if self.spawn_timer > 35:
                self.spawn_timer = 0
                lane_x = random.choice([60, 150, 240, 300])
                color = random.choice(["#ff3366", "#ffbb00", "#00f0ff", "#a855f7"])
                self.enemies.append({"x": lane_x, "y": -80, "color": color, "speed": random.randint(5, 9)})

            # Update obstacle cars
            surviving_enemies = []
            for enemy in self.enemies:
                enemy["y"] += enemy["speed"]
                # Collision detection (AABB)
                if (self.player_x < enemy["x"] + self.player_w and
                    self.player_x + self.player_w > enemy["x"] and
                    self.player_y < enemy["y"] + self.player_h and
                    self.player_y + self.player_h > enemy["y"]):
                    self.game_over = True

                if enemy["y"] < self.height + 100:
                    surviving_enemies.append(enemy)
                else:
                    self.score += 10
            self.enemies = surviving_enemies

        # Draw frame
        self.draw()
        self.root.after(20, self.update_loop)

    def draw(self):
        self.canvas.delete("all")
        # Draw road borders
        self.canvas.create_line(30, 0, 30, self.height, fill="#00f0ff", width=4)
        self.canvas.create_line(self.width - 30, 0, self.width - 30, self.height, fill="#00f0ff", width=4)
        
        # Draw central road stripes
        for y in self.road_stripes:
            self.canvas.create_line(self.width // 2, y, self.width // 2, y + 40, fill="#ffffff", width=4)

        # Draw Player Car
        px, py = self.player_x, self.player_y
        self.canvas.create_rectangle(px, py, px + self.player_w, py + self.player_h, fill="#00f0ff", outline="#ffffff", width=2)
        # Cockpit
        self.canvas.create_rectangle(px + 8, py + 15, px + self.player_w - 8, py + 40, fill="#071724", outline="")
        # Headlights
        self.canvas.create_oval(px + 4, py + 2, px + 12, py + 8, fill="#ffffff", outline="")
        self.canvas.create_oval(px + self.player_w - 12, py + 2, px + self.player_w - 4, py + 8, fill="#ffffff", outline="")

        # Draw Obstacle Cars
        for e in self.enemies:
            ex, ey = e["x"], e["y"]
            self.canvas.create_rectangle(ex, ey, ex + self.player_w, ey + self.player_h, fill=e["color"], outline="#ffffff", width=1)
            self.canvas.create_rectangle(ex + 8, ey + 25, ex + self.player_w - 8, ey + 45, fill="#111", outline="")

        # Draw HUD / Score
        self.canvas.create_text(60, 25, text=f"SCORE: {self.score}", fill="#00f0ff", font=("Segoe UI", 12, "bold"))

        if self.game_over:
            self.canvas.create_rectangle(50, 220, self.width - 50, 380, fill="#071724", outline="#ff3366", width=2)
            self.canvas.create_text(self.width // 2, 260, text="COLLISION DETECTED", fill="#ff3366", font=("Segoe UI", 16, "bold"))
            self.canvas.create_text(self.width // 2, 300, text=f"Final Score: {self.score}", fill="#ffffff", font=("Segoe UI", 12))
            self.canvas.create_text(self.width // 2, 340, text="Press 'R' to Restart | 'Q' to Quit", fill="#00f0ff", font=("Segoe UI", 10))

if __name__ == "__main__":
    app_root = tk.Tk()
    game = RacingGame(app_root)
    app_root.mainloop()
'''


