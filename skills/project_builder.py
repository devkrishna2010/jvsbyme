        self.root.title("J.A.R.V.I.S. Tactical Calculator")
        self.root.geometry("340x460")
        self.root.configure(bg="#071724")
        self.root.resizable(False, False)

        self.expr = ""
        self.display_var = tk.StringVar(value="0")

        display = tk.Entry(
            root, textvariable=self.display_var, font=("Consolas", 24, "bold"),
            bg="#02070d", fg="#00f0ff", bd=0, justify="right", insertbackground="#00f0ff"
        )
        display.pack(fill="x", padx=15, pady=20, ipady=12)

