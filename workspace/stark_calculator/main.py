"""
Autonomous Tactical Calculator — Generated by J.A.R.V.I.S. V2
Sleek dark Stark-themed expression evaluator with keyboard support.
"""
import tkinter as tk

class StarkCalculator:
    def __init__(self, root):
        self.root = root
        self.root.title("J.A.R.V.I.S. Tactical Calculator")
        self.root.geometry("340x460")
        self.root.configure(bg="#071724")
        self.root.resizable(False, False)

        self.expr = ""
        self.display_var = tk.StringVar(value="0")

        display = tk.Entry(
            root, textvariable=self.display_var, font=("Consolas", 24, "bold"),
            bg="#02070d", fg="#00f0ff", bd=0, justify="right", insertbackground="#00f0ff"
        )
        display.pack(fill="x", padx=15, pady=20, ipady=12)

        btn_frame = tk.Frame(root, bg="#071724")
        btn_frame.pack(fill="both", expand=True, padx=15, pady=(0, 20))

        buttons = [
            ('C', 0, 0, '#ff3366'), ('(', 0, 1, '#1e293b'), (')', 0, 2, '#1e293b'), ('/', 0, 3, '#0284c7'),
            ('7', 1, 0, '#0f172a'), ('8', 1, 1, '#0f172a'), ('9', 1, 2, '#0f172a'), ('*', 1, 3, '#0284c7'),
            ('4', 2, 0, '#0f172a'), ('5', 2, 1, '#0f172a'), ('6', 2, 2, '#0f172a'), ('-', 2, 3, '#0284c7'),
            ('1', 3, 0, '#0f172a'), ('2', 3, 1, '#0f172a'), ('3', 3, 2, '#0f172a'), ('+', 3, 3, '#0284c7'),
            ('0', 4, 0, '#0f172a'), ('.', 4, 1, '#0f172a'), ('DEL', 4, 2, '#475569'), ('=', 4, 3, '#00f0ff')
        ]

        for r in range(5):
            btn_frame.rowconfigure(r, weight=1)
        for c in range(4):
            btn_frame.columnconfigure(c, weight=1)

        for text, r, c, bg in buttons:
            fg = "#071724" if bg == '#00f0ff' else "#ffffff"
            btn = tk.Button(
                btn_frame, text=text, font=("Segoe UI", 12, "bold"), bg=bg, fg=fg,
                bd=0, activebackground="#38bdf8", cursor="hand2",
                command=lambda t=text: self.on_press(t)
            )
            btn.grid(row=r, column=c, sticky="nsew", padx=3, pady=3)

        self.root.bind("<Key>", self.key_press)

    def key_press(self, event):
        if event.char in "0123456789+-*/().":
            self.on_press(event.char)
        elif event.keysym == "Return":
            self.on_press("=")
        elif event.keysym in ("BackSpace", "Delete"):
            self.on_press("DEL")
        elif event.keysym == "Escape":
            self.on_press("C")

    def on_press(self, char):
        if char == "C":
            self.expr = ""
            self.display_var.set("0")
        elif char == "DEL":
            self.expr = self.expr[:-1]
            self.display_var.set(self.expr if self.expr else "0")
        elif char == "=":
            try:
                # Safe evaluation of basic math expressions
                allowed = set("0123456789+-*/.() ")
                if not all(c in allowed for c in self.expr):
                    raise ValueError("Disallowed expression")
                result = eval(self.expr)
                if isinstance(result, float) and result.is_integer():
                    result = int(result)
                self.display_var.set(str(result))
                self.expr = str(result)
            except Exception:
                self.display_var.set("Error")
                self.expr = ""
        else:
            self.expr += str(char)
            self.display_var.set(self.expr)

if __name__ == "__main__":
    root = tk.Tk()
    app = StarkCalculator(root)
    root.mainloop()
